'use strict';
const express = require('express');
const session = require('express-session');
const helmet = require('helmet');
const path = require('path');
const app = express();
const PORT = Number(process.env.PORT || 3000);
const PASSWORD = String(process.env.ADMIN_PASSWORD || '');
const SECRET = String(process.env.SESSION_SECRET || '');
if (PASSWORD.length < 12) throw new Error('ADMIN_PASSWORD must be at least 12 characters');
if (SECRET.length < 32) throw new Error('SESSION_SECRET must be at least 32 characters');
app.disable('x-powered-by');
app.set('trust proxy', 1);
app.use(helmet({ contentSecurityPolicy: false }));
app.use(express.json({ limit: '32kb' }));
app.use(session({ name:'ninja.sid', secret:SECRET, resave:false, saveUninitialized:false, cookie:{httpOnly:true,sameSite:'lax',secure:process.env.COOKIE_SECURE==='true',maxAge:8*60*60*1000} }));
const auth=(req,res,next)=>req.session?.admin ? next() : res.status(401).json({error:'Login required'});
app.get('/api/health',(_req,res)=>res.json({ok:true,name:'NINJA PANEL'}));
app.get('/api/me',(req,res)=>res.json({authenticated:!!req.session?.admin}));
app.post('/api/login',(req,res,next)=>{ if(String(req.body?.password||'')!==PASSWORD) return res.status(401).json({error:'Incorrect password'}); req.session.regenerate(err=>{if(err)return next(err);req.session.admin=true;req.session.save(err2=>err2?next(err2):res.json({ok:true}));}); });
app.post('/api/logout',auth,(req,res)=>req.session.destroy(()=>res.json({ok:true})));
app.get('/api/servers',auth,(_req,res)=>res.json({servers:[],note:'Connect a secured VPS runner to manage real bot processes.'}));
app.use(express.static(path.join(__dirname,'public')));
app.get('*',(_req,res)=>res.sendFile(path.join(__dirname,'public','index.html')));
app.listen(PORT,'0.0.0.0',()=>console.log('NINJA PANEL listening on '+PORT));
